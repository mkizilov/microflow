"""Self-contained HTML rendering of a quality-control report.

The page has no external resources. Figures are embedded as base64 PNG data URIs and the styles
are inline, so the file can be archived or attached to a CI run as it is.
"""

import base64
import html
import json
from collections.abc import Mapping

from microflow import __version__
from microflow.reporting.figures import FIGURE_TITLES
from microflow.reporting.qc import PlaneSummary, QualityReport

_STYLE = """
body { font-family: system-ui, sans-serif; margin: 2rem; color: #222; max-width: 1100px; }
h1 { font-size: 1.5rem; }
h2 { font-size: 1.15rem; margin-top: 2rem; border-bottom: 1px solid #ddd; }
table { border-collapse: collapse; }
th, td { border: 1px solid #ccc; padding: 4px 10px; text-align: right; }
th:first-child, td:first-child { text-align: left; }
.flag { color: #8a1c00; margin: 0.3rem 0; }
.figures { display: flex; flex-wrap: wrap; gap: 1rem; }
figure { margin: 0; }
figure img { max-width: 520px; border: 1px solid #ddd; }
figcaption { font-size: 0.9rem; color: #555; margin-top: 0.3rem; }
pre { background: #f6f6f6; padding: 0.8rem; overflow-x: auto; }
"""


def render_html(report: QualityReport, figures: Mapping[str, bytes]) -> str:
    escape = html.escape
    if report.flags:
        items = "".join(
            f'<li class="flag"><strong>{escape(flag.code)}</strong> '
            f"[{escape(flag.plane)}] {escape(flag.message)}</li>"
            for flag in report.flags
        )
        flags_html = f"<ul>{items}</ul>"
    else:
        flags_html = "<p>No suspicious results were flagged.</p>"

    rows = "".join(_summary_row(plane) for plane in report.planes)
    limits = _limits_text(report)
    figure_items = "".join(
        f'<figure><img alt="{escape(FIGURE_TITLES.get(name, name))}" '
        f'src="data:image/png;base64,{base64.b64encode(data).decode("ascii")}">'
        f"<figcaption>{escape(FIGURE_TITLES.get(name, name))}</figcaption></figure>"
        for name, data in figures.items()
    )
    settings = escape(json.dumps(report.settings.model_dump(mode="json"), indent=2))
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>{escape(report.title)}</title>
<style>{_STYLE}</style>
</head>
<body>
<h1>{escape(report.title)}</h1>
<p>Source: {escape(report.source)} &middot; axes: {escape(report.axes)} &middot;
length unit: {escape(report.length_unit)} &middot; figures show plane
{escape(report.figure_plane)}</p>

<h2>Flags</h2>
{flags_html}

<h2>Segmentation summary</h2>
<table>
<tr><th>Plane</th><th>Objects</th><th>Foreground</th>
<th>Area min ({escape(report.area_unit)})</th><th>Area median ({escape(report.area_unit)})</th>
<th>Area max ({escape(report.area_unit)})</th><th>Saturated</th><th>Invalid</th></tr>
{rows}
</table>
<p>{limits}</p>

<h2>Figures</h2>
<div class="figures">{figure_items}</div>

<h2>Settings</h2>
<pre>{settings}</pre>

<p style="color:#777;font-size:0.85rem">Generated by MicroFlow {escape(__version__)}.</p>
</body>
</html>
"""


def _summary_row(plane: PlaneSummary) -> str:
    cells = [
        html.escape(plane.plane),
        str(plane.object_count),
        f"{plane.foreground_fraction:.2%}",
        _cell(plane.area_min),
        _cell(plane.area_median),
        _cell(plane.area_max),
        _cell(plane.saturated_fraction, percent=True),
        f"{plane.invalid_fraction:.2%}",
    ]
    return "<tr>" + "".join(f"<td>{cell}</td>" for cell in cells) + "</tr>"


def _cell(value: float | None, percent: bool = False) -> str:
    if value is None:
        return "n/a"
    return f"{value:.2%}" if percent else f"{value:.4g}"


def _limits_text(report: QualityReport) -> str:
    if report.area_min_limit is None and report.area_max_limit is None:
        return "No object area range is configured."
    low = "none" if report.area_min_limit is None else f"{report.area_min_limit:g}"
    high = "none" if report.area_max_limit is None else f"{report.area_max_limit:g}"
    unit = html.escape(report.area_unit)
    return f"Configured object area range: {html.escape(low)} to {html.escape(high)} {unit}."
