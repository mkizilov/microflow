"""Write THIRD_PARTY_LICENSES.md from the locked environment's installed package metadata.

Run from the repository root, with the locked environment installed and ``uv`` on the PATH:

    uv run python scripts/generate_license_inventory.py          # write the file
    uv run python scripts/generate_license_inventory.py --check  # fail if it is out of date

Each row comes from the installed distribution's own metadata (License-Expression, then License,
then the License classifiers). Packages are listed as the core runtime (``uv export --no-dev``, no
extras) or as optional or development. A package reported as UNKNOWN has no license in its metadata
and needs checking by hand before redistribution.
"""

from __future__ import annotations

import importlib.metadata as metadata
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "THIRD_PARTY_LICENSES.md"
REQUIREMENT = re.compile(r"^([A-Za-z0-9_.\-]+)==([^\s;]+)")
STRONG_COPYLEFT = re.compile(r"\bA?GPL", re.IGNORECASE)
WEAK_COPYLEFT = re.compile(r"\b(L?GPL|MPL)", re.IGNORECASE)
# Platform-specific packages are absent on the machine that generates this file. Their license
# comes from a reviewed note instead, so the output stays the same offline. Checked 2026-11-08
# against the package's PyPI metadata (license classifier "BSD License"; no license field).
PLATFORM_NOTES = {
    "colorama": "BSD License (PyPI classifier; Windows-only dependency, not installed on macOS)",
}
MPL_NOTE = (
    "Distributing binaries that contain MPL-2.0 files requires their source to remain available "
    "(MPL-2.0 section 3.2). Check this before publishing a container image."
)


def _normalise(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _locked(*flags: str) -> dict[str, tuple[str, str]]:
    command = ["uv", "export", "--locked", "--no-hashes", "--no-emit-project", *flags]
    result = subprocess.run(
        [*command, "--format", "requirements-txt"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    )
    found: dict[str, tuple[str, str]] = {}
    for line in result.stdout.splitlines():
        match = REQUIREMENT.match(line)
        if match:
            found[_normalise(match.group(1))] = (match.group(1), match.group(2))
    return found


def _license(name: str) -> str:
    try:
        meta = metadata.metadata(name)
    except metadata.PackageNotFoundError:
        return PLATFORM_NOTES.get(_normalise(name), "NOT INSTALLED")
    expression = meta.get("License-Expression")
    if expression:
        return expression.strip()
    text = (meta.get("License") or "").strip()
    if text and text != "UNKNOWN" and len(text) < 120 and "\n" not in text:
        return text
    classifiers = [
        item.split("::")[-1].strip()
        for item in meta.get_all("Classifier") or []
        if item.startswith("License ::")
    ]
    return "; ".join(classifiers) or "UNKNOWN"


def _copyleft_section(title: str, found: list[str], empty: str, note: str = "") -> list[str]:
    body = empty if not found else "Review needed for: " + ", ".join(found)
    if found and note:
        body = "Present: " + ", ".join(found) + ". " + note
    return ["## " + title, "", body, ""]


def _render() -> str:
    core = _locked("--no-dev")
    everything = _locked("--all-extras", "--all-groups")
    rows = []
    for key, (name, version) in sorted(everything.items()):
        group = "core runtime" if key in core else "optional or development"
        rows.append((group, name, version, _license(name)))
    counts = Counter(row[3] for row in rows)
    strong = sorted({row[1] for row in rows if STRONG_COPYLEFT.search(row[3])})
    weak = sorted({row[1] for row in rows if WEAK_COPYLEFT.search(row[3])})
    unknown = sorted({row[1] for row in rows if row[3] == "UNKNOWN"})
    lines = [
        "# Third-party licenses",
        "",
        "<!-- Generated by scripts/generate_license_inventory.py from installed package "
        "metadata. Do not edit. -->",
        "",
        "MicroFlow is MIT licensed (see LICENSE). The packages below are separate works, each "
        "under its own license. Their license files are included in their distributions. This "
        "inventory is for review before redistribution, such as in a container image; it is not "
        "legal advice.",
        "",
        f"Packages: {len(rows)} ({len(core)} core runtime, {len(rows) - len(core)} optional or "
        "development).",
        "",
    ]
    lines += _copyleft_section("Strong copyleft licenses (GPL, AGPL)", strong, "None found.")
    lines += _copyleft_section(
        "Weak copyleft licenses (LGPL, MPL: file-level obligations)", weak, "None.", MPL_NOTE
    )
    lines += [
        "## Packages without a license in their metadata",
        "",
        "None." if not unknown else "Check by hand: " + ", ".join(unknown),
        "",
        "## Licenses in use",
        "",
        "| License | Packages |",
        "| --- | --- |",
    ]
    lines += [f"| {name} | {count} |" for name, count in sorted(counts.items())]
    lines += [
        "",
        "## All packages",
        "",
        "| Group | Package | Version | License |",
        "| --- | --- | --- | --- |",
    ]
    lines += [f"| {g} | {n} | {v} | {lic} |" for g, n, v, lic in rows]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    text = _render()
    if "--check" in argv:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != text:
            print(
                "THIRD_PARTY_LICENSES.md is out of date; run scripts/generate_license_inventory.py"
            )
            return 1
        print("THIRD_PARTY_LICENSES.md is up to date")
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
